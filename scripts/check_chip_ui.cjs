/** 本机浏览器回归：使用已安装的 Playwright，截图保存在 docs/screenshots。 */
const { execFileSync } = require('child_process');
const os = require('os');
const pwPath = process.env.PLAYWRIGHT_MODULE || require('path').join(execFileSync('npm',['root','-g'],{encoding:'utf8'}).trim(),'@playwright/cli/node_modules/playwright');
const { chromium } = require(pwPath);
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const out=path.join(__dirname,'../docs/screenshots');fs.mkdirSync(out,{recursive:true});
(async()=>{
 const cache=path.join(os.homedir(),'Library/Caches/ms-playwright');
 const cached=fs.existsSync(cache)?fs.readdirSync(cache).filter(n=>/^chromium-\d+$/.test(n)).sort().reverse().map(n=>path.join(cache,n,'chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing')).find(p=>fs.existsSync(p)):undefined;
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHIP_BROWSER_EXECUTABLE||cached});
 const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://localhost:8082');
 await page.getByText('业务服务已连接').waitFor();
 await page.screenshot({path:path.join(out,'chip-workspace-desktop.png'),fullPage:true});
 await page.locator('[data-nav=catalog]').click();
 await page.locator('#search').fill('EDU-MCU-32A');
 await page.waitForTimeout(750);
 assert.equal(await page.locator('tbody tr').count(),2);
 await page.locator('[data-part]').first().click();
 await page.getByText('QFP-48',{exact:true}).waitFor();
 await page.locator('#close-modal').click();
 await page.locator('[data-buy]').first().click();
 await page.locator('#order-form').waitFor();
 assert(Number(await page.locator('#order-qty').inputValue())>=100);
 await page.locator('#close-modal').click();
 await page.locator('[data-nav=inventory]').click();
 await page.locator('#warning-only').check();
 await page.waitForTimeout(250);
 assert.equal(await page.locator('tbody tr').count(),4);
 await page.locator('[data-nav=orders]').click();
 await page.locator('#status-filter').selectOption('1');
 await page.waitForTimeout(250);
 assert(await page.locator('tbody tr').count()>0);
 await page.locator('[data-order]').first().click();
 await page.locator('#status-form').waitFor();
 await page.locator('#close-modal').click();
 await page.locator('[data-nav=suppliers]').click();
 await page.waitForTimeout(250);
 assert.equal(await page.locator('.supplier-card').count(),6);
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://localhost:8082');
 await page.getByText('业务服务已连接').waitFor();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(out,'chip-workspace-mobile.png'),fullPage:true});
 // Agent 前端的历史请求依赖真实 API；此处验证正常布局和建议动作，后端另有真实 MySQL 回归。
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://localhost:3000');
 await page.getByText('从一颗芯片，开始下一步决策。').waitFor();
 assert.equal(await page.locator('.feature-item').count(),4);
 await page.screenshot({path:path.join(out,'chip-assistant-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(out,'chip-assistant-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: desktop/mobile, navigation, chip search, filters, order forms and assistant landing; four screenshots saved.');
})().catch(e=>{console.error(e);process.exit(1)});
